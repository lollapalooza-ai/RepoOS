import time
import ctypes
import os
from rich.console import Console
from rich.table import Table

console = Console()
DYLIB_PATH = "./.poly_cache3/legacy_shop_heavy_math_compute_gravity.dylib"

# --- 1. The Baseline Python Logic ---
def compute_gravity_py(m1: float, m2: float) -> float:
    """Standard CPython execution path"""
    result = (m1 * m2) / 9.81
    result = result + (m1 * 0.5)
    result = result - (m2 * 0.2)
    return result

# --- 2. The AOT Library Loader ---
def load_aot_kernel():
    if not os.path.exists(DYLIB_PATH):
        raise FileNotFoundError(f"AOT Library missing! {DYLIB_PATH}")
    
    # Load the native machine code
    lib = ctypes.CDLL(DYLIB_PATH)
    
    # Symbols generated by 'llvm-request-c-wrappers' use the '_mlir_ciface_' prefix
    # but also provide the direct symbol if the ABI matches.
    # On ARM64, the direct symbol often works for scalar doubles.
    try:
        func = lib.compute_gravity
    except AttributeError:
        # Fallback to the ciface wrapper which usually uses out-parameters for return
        func_ciface = lib._mlir_ciface_compute_gravity
        
        # MLIR C-Interface for double f(double, double) is:
        # void _mlir_ciface_f(double* res, double a1, double a2)
        func_ciface.argtypes = [ctypes.POINTER(ctypes.c_double), ctypes.c_double, ctypes.c_double]
        func_ciface.restype = None
        
        def wrapper(m1, m2):
            res = ctypes.c_double(0.0)
            func_ciface(ctypes.byref(res), m1, m2)
            return res.value
        return wrapper

    # If direct symbol found, use standard C convention
    func.argtypes = [ctypes.c_double, ctypes.c_double]
    func.restype = ctypes.c_double
    return func

def run_micro_benchmark():
    console.print(f"\n[bold cyan]🔬 Running AOT-Compiled MLIR Performance Validation (1,000,000 Iterations)...[/bold cyan]")
    
    ITERATIONS = 1_000_000
    m1, m2 = 5000.0, 1200.0

    try:
        jit_func = load_aot_kernel()
    except Exception as e:
        console.print(f"[bold red]❌ Failed to load AOT Kernel: {e}[/bold red]")
        return
        
    # Warmup
    jit_func(m1, m2)

    # --- Poly-Kernel: MLIR (AOT) ---
    start_jit = time.perf_counter()
    for _ in range(ITERATIONS):
        jit_res = jit_func(m1, m2)
    jit_time = time.perf_counter() - start_jit

    # --- Baseline: CPython ---
    start_py = time.perf_counter()
    for _ in range(ITERATIONS):
        py_res = compute_gravity_py(m1, m2) 
    py_time = time.perf_counter() - start_py

    # --- Sanity Check ---
    assert abs(py_res - jit_res) < 1e-10, f"Math Mismatch! Py: {py_res}, MLIR: {jit_res}"

    # --- Render Dashboard ---
    table = Table(title="Pure Math Loop: CPython vs Poly-Kernel (AOT MLIR)", style="cyan")
    table.add_column("Architecture", style="dim")
    table.add_column("Final Result", justify="right")
    table.add_column("Execution time", justify="right")

    table.add_row("CPython", f"{py_res:.6f}", f"[red]{py_time:.4f}s[/red]")
    
    speedup = py_time / jit_time if jit_time > 0 else float('inf')
    table.add_row("Poly-Kernel (AOT MLIR)", f"{jit_res:.6f}", f"[bold green]{jit_time:.4f}s[/bold green] ({speedup:.1f}x Faster)")
    
    console.print("\n", table)

if __name__ == "__main__":
    run_micro_benchmark()
